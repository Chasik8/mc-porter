/**
 * Three invented "versions" (no Minecraft data): 3.0 (Mojang-style names), 2.0 (Mojang + SRG/MCP, the stitch point) and
 * 1.0 (SRG/MCP only), with obfuscated jars generated by ASM and mapping files in the real formats.
 *
 * <ul>
 *   <li>com.example.Level#getThing(int): same in 3.0/2.0, SRG id kept, MCP renamed it getThingOld in 1.0;</li>
 *   <li>com.example.Thing#tick(): SRG id changed between 2.0 and 1.0, MCP name "update" kept -> name fallback;</li>
 *   <li>com.example.NewStuff exists only in 3.0 -> removed.</li>
 * </ul>
 */
final class SyntheticWorld {
    private SyntheticWorld() {
    }

    /** Writes everything into {@code cache/dl/...} and returns the matching manifest. */
    static Sources create(Path cache) throws IOException {
        List<Map<String, Object>> versions = new ArrayList<>();
        // 3.0: a = Level { int b; b a(int) }, b = Thing { void a() }, c = NewStuff
        Path jar3 = jar(cache, "jar-3.0", List.of(
                cls("a", List.of(new M("a", "(I)Lb;", "thing-lookup")), List.of(new F("b", "I"))),
                cls("b", List.of(new M("a", "()V", "thing-tick")), List.of()),
                cls("c", List.of(new M("a", "()V", "brand-new")), List.of())));
        String pg3 = """
                com.example.Level -> a:
                    int counter -> b
                    com.example.Thing getThing(int) -> a
                com.example.Thing -> b:
                    void tick() -> a
                com.example.NewStuff -> c:
                    void hello() -> a
                """;
        Path moj3 = file(cache, "moj-3.0", "client.txt", pg3);
        versions.add(version("3.0", "mojmap", jar3, List.of(art("proguard", moj3, null))));

        // 2.0: x = Level { int w; z y(int) }, z = Thing { void q() }
        Path jar2 = jar(cache, "jar-2.0", List.of(
                cls("x", List.of(new M("y", "(I)Lz;", "thing-lookup")), List.of(new F("w", "I"))),
                cls("z", List.of(new M("q", "()V", "thing-tick")), List.of())));
        Path moj2 = file(cache, "moj-2.0", "client.txt", """
                com.example.Level -> x:
                    int counter -> w
                    com.example.Thing getThing(int) -> y
                com.example.Thing -> z:
                    void tick() -> q
                """);
        Path tsrg2 = zip(cache, "srg-2.0", "config.zip", Map.of("config/joined.tsrg", """
                x com/example/World
                \ty (I)Lz; func_100_a
                \tw field_200_b
                z com/example/Thing
                \tq ()V func_300_c
                """));
        Path csv2 = zip(cache, "csv-2.0", "mcp.zip", Map.of(
                "methods.csv", "searge,name,side,desc\nfunc_100_a,getThing,2,\nfunc_300_c,update,2,\n",
                "fields.csv", "searge,name,side,desc\nfield_200_b,counter,2,\n",
                "params.csv", "param,name,side\np_100_1_,index,2\n"));
        versions.add(version("2.0", "mojmap", jar2, List.of(art("proguard", moj2, null), art("tsrg", tsrg2, "config/joined.tsrg"),
                art("mcp-csv", csv2, null))));

        // 1.0: k = World { int n; l m(int) }, l = Thing { void o() }  (new SRG id for o)
        Path jar1 = jar(cache, "jar-1.0", List.of(
                cls("k", List.of(new M("m", "(I)Ll;", "thing-lookup")), List.of(new F("n", "I"))),
                cls("l", List.of(new M("o", "()V", "thing-tick")), List.of())));
        Path srg1 = zip(cache, "srg-1.0", "srg.zip", Map.of("joined.srg", """
                CL: k com/example/World
                CL: l com/example/Thing
                FD: k/n com/example/World/field_200_b
                MD: k/m (I)Ll; com/example/World/func_100_a (I)Lcom/example/Thing;
                MD: l/o ()V com/example/Thing/func_301_d ()V
                """));
        Path csv1 = zip(cache, "csv-1.0", "mcp.zip", Map.of(
                "methods.csv", "searge,name,side,desc\nfunc_100_a,getThingOld,2,\nfunc_301_d,update,2,\n",
                "fields.csv", "searge,name,side,desc\nfield_200_b,counter,2,\n",
                "params.csv", "param,name,side\n"));
        versions.add(version("1.0", "mcp", jar1, List.of(art("srg", srg1, "joined.srg"), art("mcp-csv", csv1, null))));
        return Sources.parse(Json.json().valueToTree(Map.of("versions", versions)));
    }

    record M(String name, String desc, String marker) {
    }

    record F(String name, String desc) {
    }

    record C(String name, List<M> methods, List<F> fields) {
    }

    static C cls(String name, List<M> methods, List<F> fields) {
        return new C(name, methods, fields);
    }

    private static Map<String, Object> version(String id, String canonical, Path jar, List<Map<String, Object>> maps) throws IOException {
        Map<String, Object> v = new LinkedHashMap<>();
        v.put("id", id);
        v.put("canonical", canonical);
        v.put("jar", art("jar", jar, null));
        v.put("mappings", maps);
        return v;
    }

    private static Map<String, Object> art(String type, Path file, String entry) throws IOException {
        Map<String, Object> a = new LinkedHashMap<>();
        a.put("type", type);
        a.put("name", type);
        a.put("version", "test");
        a.put("dir", file.getParent().getFileName().toString());
        a.put("url", "https://example.invalid/" + file.getFileName());
        a.put("sha1", sha1(file));
        if (entry != null) {
            a.put("entry", entry);
        }
        return a;
    }

    private static String sha1(Path p) throws IOException {
        try {
            return HexFormat.of().formatHex(MessageDigest.getInstance("SHA-1").digest(Files.readAllBytes(p)));
        } catch (java.security.NoSuchAlgorithmException e) {
            throw new IllegalStateException(e);
        }
    }

    private static Path file(Path cache, String dir, String name, String text) throws IOException {
        Path p = cache.resolve("dl").resolve(dir).resolve(name);
        Files.createDirectories(p.getParent());
        Files.writeString(p, text, StandardCharsets.UTF_8);
        return p;
    }

    private static Path zip(Path cache, String dir, String name, Map<String, String> entries) throws IOException {
        Path p = cache.resolve("dl").resolve(dir).resolve(name);
        Files.createDirectories(p.getParent());
        try (OutputStream o = Files.newOutputStream(p); ZipOutputStream z = new ZipOutputStream(o)) {
            for (Map.Entry<String, String> e : new java.util.TreeMap<>(entries).entrySet()) {
                ZipEntry ze = new ZipEntry(e.getKey());
                ze.setTime(0);
                z.putNextEntry(ze);
                z.write(e.getValue().getBytes(StandardCharsets.UTF_8));
                z.closeEntry();
            }
        }
        return p;
    }

    private static Path jar(Path cache, String dir, List<C> classes) throws IOException {
        Map<String, byte[]> out = new java.util.TreeMap<>();
        for (C c : classes) {
            ClassWriter cw = new ClassWriter(ClassWriter.COMPUTE_FRAMES | ClassWriter.COMPUTE_MAXS);
            cw.visit(Opcodes.V1_8, Opcodes.ACC_PUBLIC, c.name(), null, "java/lang/Object", null);
            for (F f : c.fields()) {
                cw.visitField(Opcodes.ACC_PUBLIC, f.name(), f.desc(), null, null).visitEnd();
            }
            MethodVisitor init = cw.visitMethod(Opcodes.ACC_PUBLIC, "<init>", "()V", null, null);
            init.visitCode();
            init.visitVarInsn(Opcodes.ALOAD, 0);
            init.visitMethodInsn(Opcodes.INVOKESPECIAL, "java/lang/Object", "<init>", "()V", false);
            init.visitInsn(Opcodes.RETURN);
            init.visitMaxs(0, 0);
            init.visitEnd();
            for (M m : c.methods()) {
                MethodVisitor mv = cw.visitMethod(Opcodes.ACC_PUBLIC, m.name(), m.desc(), null, null);
                mv.visitCode();
                mv.visitLdcInsn(m.marker());
                mv.visitInsn(Opcodes.POP);
                if (m.desc().endsWith(")V")) {
                    mv.visitInsn(Opcodes.RETURN);
                } else {
                    mv.visitInsn(Opcodes.ACONST_NULL);
                    mv.visitInsn(Opcodes.ARETURN);
                }
                mv.visitMaxs(0, 0);
                mv.visitEnd();
            }
            cw.visitEnd();
            out.put(c.name() + ".class", cw.toByteArray());
        }
        Path p = cache.resolve("dl").resolve(dir).resolve("client.jar");
        Files.createDirectories(p.getParent());
        try (OutputStream o = Files.newOutputStream(p); ZipOutputStream z = new ZipOutputStream(o)) {
            for (Map.Entry<String, byte[]> e : out.entrySet()) {
                ZipEntry ze = new ZipEntry(e.getKey());
                ze.setTime(0);
                z.putNextEntry(ze);
                z.write(e.getValue());
                z.closeEntry();
            }
        }
        return p;
    }
}

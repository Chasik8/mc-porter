package dev.porter.generate;

import com.squareup.javapoet.JavaFile;
import com.squareup.javapoet.TypeSpec;
import dev.porter.core.json.Json;
import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.SortedMap;
import java.util.TreeMap;
import tools.jackson.databind.JsonNode;

/**
 * The generated tree, kept in memory (sorted by path) and written in one go. Text is UTF-8 with LF line ends; no
 * timestamps anywhere, so equal input gives byte-identical output.
 */
public final class GenOutput {
    /** Manifest written at the output root; lists every generated file so a rerun can remove stale ones. */
    public static final String MANIFEST = "porter-generate.json";
    public static final String JAVA_ROOT = "src/main/java/";
    public static final String RESOURCES_ROOT = "src/main/resources/";
    static final String HEADER = "Generated by porter generate from IR. Do not edit: regenerate instead.";
    static final String STUB_HEADER = "porter:stub - placeholder for a logic class; replaced by the rewriter output.\n"
            + "Keep the superclass and the constructor signature when replacing it.";

    private final SortedMap<String, byte[]> files = new TreeMap<>();
    private final SortedMap<String, String> stubs = new TreeMap<>();

    /** Adds a generated Java type. */
    public void addJava(String pkg, TypeSpec type) {
        put(javaPath(pkg, type.name), render(pkg, type, HEADER));
    }

    /**
     * Adds a stub for a logic class referenced by IR ({@code logicClass}, {@code screenClass}, {@code handlerClass}).
     *
     * @param role what the class is (block, blockEntity, menu, ...) — recorded in the manifest
     */
    public void addStub(String pkg, TypeSpec type, String role) {
        String path = javaPath(pkg, type.name);
        put(path, render(pkg, type, STUB_HEADER));
        stubs.put((pkg.isEmpty() ? "" : pkg + ".") + type.name, role);
    }

    public boolean hasJava(String fqn) {
        return files.containsKey(JAVA_ROOT + fqn.replace('.', '/') + ".java");
    }

    private static String javaPath(String pkg, String name) {
        return JAVA_ROOT + (pkg.isEmpty() ? "" : pkg.replace('.', '/') + "/") + name + ".java";
    }

    private static String render(String pkg, TypeSpec type, String header) {
        return JavaFile.builder(pkg, type).addFileComment(header).indent("    ").skipJavaLangImports(true).build()
                .toString();
    }

    public void put(String path, String text) {
        put(path, text.replace("\r\n", "\n").getBytes(StandardCharsets.UTF_8));
    }

    public void put(String path, byte[] content) {
        if (files.containsKey(path) && !Arrays.equals(files.get(path), content)) {
            throw new IllegalStateException("two different contents for " + path);
        }
        files.put(path, content);
    }

    /** Adds a JSON resource, pretty-printed with the shared mapper. */
    public void putJson(String path, Object value) {
        put(path, Json.json().writeValueAsString(value) + "\n");
    }

    public SortedMap<String, byte[]> files() {
        return files;
    }

    public SortedMap<String, String> stubs() {
        return stubs;
    }

    /**
     * Writes all files below {@code out} and deletes files listed in a previous manifest that are no longer generated.
     * Files that were not generated by porter are never touched.
     *
     * @return number of stale files removed
     */
    public int write(Path out, Map<String, Object> manifest) {
        try {
            Files.createDirectories(out);
            Path mf = out.resolve(MANIFEST);
            int removed = 0;
            if (Files.isRegularFile(mf)) {
                JsonNode old = Json.json().readTree(Files.readString(mf));
                for (JsonNode f : old.path("files")) {
                    String p = f.asString();
                    if (!files.containsKey(p) && !p.contains("..")) {
                        if (Files.deleteIfExists(out.resolve(p))) {
                            removed++;
                        }
                    }
                }
            }
            for (Map.Entry<String, byte[]> e : files.entrySet()) {
                Path p = out.resolve(e.getKey());
                Files.createDirectories(p.getParent());
                if (!Files.isRegularFile(p) || !Arrays.equals(Files.readAllBytes(p), e.getValue())) {
                    Files.write(p, e.getValue());
                }
            }
            Map<String, Object> m = new LinkedHashMap<>(manifest);
            m.put("stubs", stubs);
            m.put("files", new ArrayList<>(files.keySet()));
            Files.writeString(mf, Json.json().writeValueAsString(m).replace("\r\n", "\n") + "\n", StandardCharsets.UTF_8);
            return removed;
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    /** Paths of generated Java sources. */
    public List<String> javaFiles() {
        return files.keySet().stream().filter(p -> p.startsWith(JAVA_ROOT)).toList();
    }
}

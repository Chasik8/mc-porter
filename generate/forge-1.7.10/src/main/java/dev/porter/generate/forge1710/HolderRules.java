package dev.porter.generate.forge1710;

import dev.porter.core.ir.IrNode;
import dev.porter.generate.GenContext;
import dev.porter.generate.Names;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;
import tools.jackson.databind.JsonNode;

/**
 * Rewrite rules from the source mod's registry holder fields to the generated content ({@code porter-rules/holders.rule.yaml}):
 * logic code ported whole still reads {@code ModItems.CUP}; the object is now created by the generated content class,
 * so every holder field the extractor recorded ({@code porter-extract:holders}) becomes a field rule
 * {@code ModItems#CUP -> <Mod>Content.itemCup}. Pass the file to {@code porter rewrite --rules}. One rule per holder,
 * each with a test; deterministic.
 */
final class HolderRules {
    static final String HOLDERS = "porter-extract:holders";
    static final String PATH = "porter-rules/holders.rule.yaml";

    private final Plan plan;
    private final GenContext ctx;

    HolderRules(Plan plan) {
        this.plan = plan;
        this.ctx = plan.ctx;
    }

    void run() {
        Map<String, String> rules = new TreeMap<>(); // holder -> replacement
        String content = plan.content.simpleName();
        for (IrNode.Block b : ctx.ir.all(IrNode.Block.class)) {
            if (FluidGen.fluidOfBlock(ctx, b.id()).isEmpty()) {
                holders(b).forEach(h -> rules.put(h, content + "." + ContentGen.blockField(b.id())));
            }
        }
        for (IrNode.Item i : ctx.ir.all(IrNode.Item.class)) {
            String repl = i.placesBlock() != null
                    ? "Item.getItemFromBlock(" + content + "." + ContentGen.blockField(i.placesBlock()) + ")"
                    : content + "." + ContentGen.itemField(i.id());
            holders(i).forEach(h -> rules.put(h, repl));
        }
        for (IrNode.Fluid f : ctx.ir.all(IrNode.Fluid.class)) {
            holders(f).forEach(h -> rules.put(h, content + "." + FluidGen.field(f.id())));
        }
        for (IrNode.Effect e : ctx.ir.all(IrNode.Effect.class)) {
            holders(e).forEach(h -> rules.put(h, content + "." + PotionGen.field(e.id())));
        }
        if (rules.isEmpty()) {
            return;
        }
        StringBuilder sb = new StringBuilder("# Generated by porter generate: the source mod's registry holder fields -> the generated content.\n"
                + "# Use with porter rewrite --rules (the logic code ported whole reads these holders).\n");
        boolean first = true;
        for (Map.Entry<String, String> r : rules.entrySet()) {
            String holder = r.getKey();
            String owner = holder.substring(0, holder.indexOf('#'));
            String field = holder.substring(holder.indexOf('#') + 1);
            String simple = owner.substring(owner.lastIndexOf('.') + 1);
            List<String> imports = new ArrayList<>(List.of(plan.content.canonicalName()));
            if (r.getValue().startsWith("Item.")) {
                imports.add("net.minecraft.item.Item");
            }
            if (!first) {
                sb.append("---\n");
            }
            first = false;
            sb.append("schemaVersion: 1\n")
                    .append("id: r-gen-holder-").append(slug(simple + "-" + field)).append('\n')
                    .append("description: \"").append(q("holder " + holder + " -> generated content " + r.getValue())).append("\"\n")
                    .append("from: forge-1.19.2\nto: forge-1.7.10\nkind: adapter\nmatch:\n")
                    .append("  field: \"").append(q(holder)).append("\"\n")
                    .append("replace: \"").append(q(r.getValue())).append("\"\n")
                    .append("imports: [").append(String.join(", ", imports.stream().map(i -> "\"" + i + "\"").toList())).append("]\n")
                    .append("confidence: 1.0\n")
                    .append("provenance: { source: mined, ref: \"porter generate: IR porter-extract:holders + generated field names\" }\n")
                    .append("tests:\n")
                    .append("  - context: \"import ").append(q(owner)).append("\"\n")
                    .append("    before: \"Object o = ").append(simple).append('.').append(field).append(";\"\n")
                    .append("    after: \"Object o = ").append(q(r.getValue())).append(";\"\n");
        }
        ctx.out.put(PATH, sb.toString());
        ctx.info("holder-rules", PATH, rules.size() + " registry holder fields -> generated content (porter rewrite --rules)");
    }

    private static List<String> holders(IrNode n) {
        List<String> out = new ArrayList<>();
        JsonNode h = n.extensions() == null ? null : n.extensions().get(HOLDERS);
        if (h != null && h.isArray()) {
            h.forEach(x -> out.add(x.asString()));
        }
        return out;
    }

    private static String slug(String s) {
        return Names.path(s).toLowerCase(java.util.Locale.ROOT).replaceAll("[^a-z0-9]+", "-").replaceAll("^-|-$", "");
    }

    private static String q(String s) {
        return s.replace("\\", "\\\\").replace("\"", "\\\"");
    }
}

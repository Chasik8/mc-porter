package dev.porter.port;

import dev.porter.core.cli.ExitCodes;
import dev.porter.core.cli.PorterSubcommand;
import dev.porter.core.cli.RunReport;
import dev.porter.core.contract.Contract;
import dev.porter.core.contract.ContractValidator;
import dev.porter.core.json.Json;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.concurrent.Callable;
import picocli.CommandLine;
import picocli.CommandLine.Command;
import picocli.CommandLine.Option;
import tools.jackson.databind.JsonNode;

/**
 * {@code porter catalog}: the table of ports in {@code ports/README.md} is generated from {@code ports/catalog.yaml}
 * between the markers {@code <!-- catalog:begin -->} and {@code <!-- catalog:end -->}; {@code --check} fails when the
 * file is out of date (used by scripts/check.sh).
 */
@Command(name = "catalog", description = {"Generate the table of ports (ports/README.md) from ports/catalog.yaml.",
        "Without --write the table is printed; with --check the command fails when ports/README.md is out of date."})
public final class CatalogCommand implements PorterSubcommand, Callable<Integer> {
    static final String BEGIN = "<!-- catalog:begin (generated by `porter catalog --write`, do not edit by hand) -->";
    static final String END = "<!-- catalog:end -->";

    @CommandLine.Spec
    CommandLine.Model.CommandSpec spec;

    @Option(names = {"-h", "--help"}, usageHelp = true, description = "Show this help message and exit.")
    boolean help;

    @Option(names = "--catalog", paramLabel = "<file>", description = "The catalog (default ports/catalog.yaml).")
    Path catalog = Path.of("ports/catalog.yaml");

    @Option(names = "--readme", paramLabel = "<file>", description = "The README holding the table (default ports/README.md).")
    Path readme = Path.of("ports/README.md");

    @Option(names = "--write", description = "Update the table in the README.")
    boolean write;

    @Option(names = "--check", description = "Fail when the table in the README differs from the catalog.")
    boolean check;

    @Override
    public String path() {
        return "catalog";
    }

    @Override
    public Integer call() {
        RunReport report = new RunReport("catalog", new ArrayList<>(spec.commandLine().getParseResult().originalArgs()));
        ContractValidator.FileResult v = ContractValidator.get().validateFile(catalog, Contract.PORT_CATALOG);
        if (!v.valid()) {
            System.err.println("porter catalog: " + catalog + " is not valid");
            v.issues().forEach(i -> System.err.println("    " + i));
            report.write(RunReport.STATUS_FAILED, ExitCodes.USAGE);
            return ExitCodes.USAGE;
        }
        String table = table(Json.yaml().readTree(dev.porter.port.Text.read(catalog)));
        if (!write && !check) {
            System.out.print(table);
            report.write(RunReport.STATUS_OK, ExitCodes.OK);
            return ExitCodes.OK;
        }
        String text = Files.isRegularFile(readme) ? dev.porter.port.Text.read(readme) : "";
        int a = text.indexOf(BEGIN);
        int b = text.indexOf(END);
        if (a < 0 || b < a) {
            System.err.println("porter catalog: " + readme + " has no catalog markers (" + BEGIN + " ... " + END + ")");
            report.write(RunReport.STATUS_FAILED, ExitCodes.USAGE);
            return ExitCodes.USAGE;
        }
        String updated = text.substring(0, a) + BEGIN + "\n\n" + table + "\n" + text.substring(b);
        if (check) {
            boolean same = updated.equals(text);
            System.out.println(same ? readme + " is up to date" : readme + " is out of date: run `porter catalog --write`");
            report.write(same ? RunReport.STATUS_OK : RunReport.STATUS_FAILED, same ? ExitCodes.OK : ExitCodes.FAILED);
            return same ? ExitCodes.OK : ExitCodes.FAILED;
        }
        dev.porter.port.Text.write(readme, updated);
        System.out.println("wrote " + readme);
        report.write(RunReport.STATUS_OK, ExitCodes.OK);
        return ExitCodes.OK;
    }

    static String table(JsonNode cat) {
        StringBuilder sb = new StringBuilder();
        sb.append("| Mod | Version | Ported | Mode | Status | Scenarios | Licence | Jar may be shared | How to run |\n");
        sb.append("|---|---|---|---|---|---|---|---|---|\n");
        List<JsonNode> ports = new ArrayList<>();
        cat.path("ports").forEach(ports::add);
        ports.sort((x, y) -> x.path("mod").path("name").asString().compareToIgnoreCase(y.path("mod").path("name").asString()));
        for (JsonNode p : ports) {
            JsonNode mod = p.path("mod");
            String name = mod.has("url") ? "[" + mod.path("name").asString() + "](" + mod.get("url").asString() + ")" : mod.path("name").asString();
            String profile = p.path("profile").asString("");
            String how = profile.isEmpty() ? "-" : "[" + profile.replaceFirst("^ports/", "") + "](" + profile.replaceFirst("^ports/", "") + "/README.md)";
            String rate = p.has("scenarioPassRate") ? Math.round(p.get("scenarioPassRate").asDouble() * 100) + "%" : "-";
            sb.append("| ").append(name).append(" | ").append(mod.path("version").asString()).append(" | ")
                    .append(p.path("from").asString().replace("forge-", "")).append(" → ").append(p.path("to").asString().replace("forge-", ""))
                    .append(" | ").append(p.path("mode").asString()).append(" | ").append(p.path("status").asString()).append(" | ")
                    .append(rate).append(" | ").append(p.path("licence").asString()).append(" | ")
                    .append(p.path("distributable").asBoolean() ? "yes" : "no").append(" | ").append(how).append(" |\n");
        }
        return sb.toString();
    }
}

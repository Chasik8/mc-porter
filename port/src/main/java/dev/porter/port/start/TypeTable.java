package dev.porter.port.start;

import java.io.DataInputStream;
import java.io.IOException;
import java.io.InputStream;
import java.io.Writer;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Enumeration;
import java.util.List;
import java.util.TreeMap;
import java.util.zip.ZipEntry;
import java.util.zip.ZipFile;

/**
 * Supertype table (the rewriter's {@code --type-facts} TSV) of every class in some jars: class, superclass,
 * interfaces, access flags. Reads class-file headers only; nothing is loaded or executed. Java port of
 * {@code rewrite/scripts/typefacts_from_jars.py}, so a player needs no Python.
 */
public final class TypeTable {
    private TypeTable() {
    }

    private record Row(String sup, List<String> ifs, int acc) {
    }

    public static int write(Path out, List<Path> jars, List<String> prefixes) {
        TreeMap<String, Row> rows = new TreeMap<>();
        for (Path jar : jars) {
            try (ZipFile z = new ZipFile(jar.toFile())) {
                for (Enumeration<? extends ZipEntry> en = z.entries(); en.hasMoreElements();) {
                    ZipEntry e = en.nextElement();
                    String n = e.getName();
                    if (!n.endsWith(".class") || n.startsWith("META-INF/") || n.endsWith("module-info.class")) {
                        continue;
                    }
                    try (InputStream in = z.getInputStream(e)) {
                        parse(in.readAllBytes(), prefixes, rows);
                    }
                }
            } catch (IOException e) {
                throw new Fail("cannot read " + jar + ": " + e.getMessage(), e);
            }
        }
        try {
            Files.createDirectories(out.getParent());
            try (Writer w = Files.newBufferedWriter(out, StandardCharsets.UTF_8)) {
                w.write("# class\tsuper\tinterfaces\taccess (generated by porter run from the Minecraft and Forge jars)\n");
                for (var e : rows.entrySet()) {
                    Row r = e.getValue();
                    w.write(e.getKey() + "\t" + r.sup() + "\t" + String.join(",", r.ifs()) + "\t" + r.acc() + "\n");
                }
            }
        } catch (IOException e) {
            throw new Fail("cannot write " + out, e);
        }
        return rows.size();
    }

    private static void parse(byte[] b, List<String> prefixes, TreeMap<String, Row> rows) throws IOException {
        DataInputStream d = new DataInputStream(new java.io.ByteArrayInputStream(b));
        if (d.readInt() != 0xCAFEBABE) {
            return;
        }
        d.readUnsignedShort();
        d.readUnsignedShort();
        int n = d.readUnsignedShort();
        String[] utf = new String[n];
        int[] cls = new int[n];
        for (int k = 1; k < n; k++) {
            int tag = d.readUnsignedByte();
            switch (tag) {
                case 1 -> utf[k] = d.readUTF();
                case 7 -> cls[k] = d.readUnsignedShort();
                case 8, 16, 19, 20 -> d.skipBytes(2);
                case 15 -> d.skipBytes(3);
                case 3, 4, 9, 10, 11, 12, 17, 18 -> d.skipBytes(4);
                case 5, 6 -> {
                    d.skipBytes(8);
                    k++;
                }
                default -> {
                    return;
                }
            }
        }
        int access = d.readUnsignedShort();
        int self = d.readUnsignedShort();
        int sup = d.readUnsignedShort();
        int ni = d.readUnsignedShort();
        String name = cname(self, cls, utf);
        if (!prefixes.isEmpty() && prefixes.stream().noneMatch(name::startsWith)) {
            return;
        }
        List<String> ifs = new ArrayList<>();
        for (int j = 0; j < ni; j++) {
            ifs.add(cname(d.readUnsignedShort(), cls, utf));
        }
        rows.putIfAbsent(name, new Row(cname(sup, cls, utf), ifs, access));
    }

    private static String cname(int idx, int[] cls, String[] utf) {
        return idx == 0 ? "" : utf[cls[idx]].replace('/', '.');
    }
}

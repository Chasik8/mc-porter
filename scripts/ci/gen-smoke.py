#!/usr/bin/env python3
"""Writes the automatic smoke scenario of a port: gen-smoke.py <port-dir> <ir-dir> <out.scenario.yaml>

The scenario starts the server with the mod, ticks once and asserts that every block and item of the IR (extracted from
the original mod's sources) is registered under the mod's namespace. Without an IR (or one without blocks/items) it only
requires something to be registered. "No exceptions in the log" is checked by smoke-log-check.sh on the server log.
"""
import json
import re
import sys
from pathlib import Path

import yaml

port_dir, ir_dir, out = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3])
cfg = yaml.safe_load(next(port_dir.glob("*.port.yaml")).read_text(encoding="utf-8"))

modid = None
for unit in (cfg.get("generate") or {}).get("units", []) or []:
    args = unit.get("args", [])
    if "--modid" in args:
        modid = args[args.index("--modid") + 1]
blocks = items = 0
if ir_dir.is_dir():
    for f in sorted(ir_dir.rglob("*.json")):
        try:
            data = json.loads(f.read_text(encoding="utf-8"))
        except ValueError:
            continue
        for n in data.get("nodes", []) if isinstance(data, dict) else []:
            kind, nid = n.get("kind"), str(n.get("id", ""))
            if kind == "mod" and not modid:
                modid = nid
            if ":" in nid and (modid is None or nid.startswith(modid + ":")):
                blocks += kind == "block"
                items += kind == "item"
modid = modid or cfg.get("name") or port_dir.name
name = re.sub(r"[^a-z0-9._-]", "-", str(cfg.get("name", port_dir.name)).lower())

steps = [
    "  - tick: 1",
    f'  - sample: {{ what: ["registry:blocks/{modid}:", "registry:items/{modid}:"] }}',
]
if blocks or items:
    steps.append(f'  - assert: {{ expr: "len(registry:blocks/{modid}:) >= {blocks}", message: "{blocks} blocks of the IR are registered" }}')
    steps.append(f'  - assert: {{ expr: "len(registry:items/{modid}:) >= {items}", message: "{items} items of the IR are registered" }}')
else:
    steps.append(f'  - assert: {{ expr: "len(registry:blocks/{modid}:) + len(registry:items/{modid}:) >= 1", message: "the mod registers something" }}')

out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("\n".join([
    "schemaVersion: 1",
    f"id: smoke-{name}",
    "description: >-",
    f"  Automatic smoke test generated by CI: the server starts with the mod and its blocks ({blocks}) and items ({items}) from the IR",
    "  are registered.",
    "world: flat-void",
    "maxTicks: 50",
    "tolerance:",
    '  "*": { abs: 0 }',
    "steps:",
    *steps,
    "",
]), encoding="utf-8")
print(f"smoke scenario {out}: namespace {modid}, {blocks} blocks, {items} items from the IR")

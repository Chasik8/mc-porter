"""Compact spec of the rules that map Forge 1.19.2 API onto the adapters of this directory (dev.porter.shim.mc).
Writes rules/packs/adapters/1.19.2__1.7.10/modern-api-<topic>.rule.yaml (part of the opt-in adapter pack) (one rule per symbol, each with a before/after
test). Deterministic. Usage: python -I rules_spec.py"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = HERE
S = 'dev.porter.shim.mc.'
REF = 'demo port (TorchMaster): one rule per distinct javac symbol; source = Mojang 1.19.2 mappings / Forge 43.5.2, target = MCP 1.7.10 / adapter pack (rewrite/shim/src/adapters)'


def q(s):
    return s.replace('\\', '\\\\').replace('"', '\\"')


class Rules:
    def __init__(self, topic, header, ref=None):
        self.topic, self.header, self.out, self.ids = topic, header, [], set()
        self.ref = ref or REF

    def _id(self, slug):
        i = ('r-1.19.2-1.7.10-' + slug).lower().replace('$', '-').replace('_', '-')
        n, k = i, 2
        while n in self.ids:
            n, k = f'{i}-{k}', k + 1
        self.ids.add(n)
        return n

    def add(self, slug, sel, m, r, tests, kind='adapter', bind=None, imports=None, pre=None, prio=None):
        s = f'schemaVersion: 1\nid: {self._id(slug)}\ndescription: "{q(sel + " " + m + " -> " + r)}"\n'
        s += f'from: forge-1.19.2\nto: forge-1.7.10\nkind: {kind}\nmatch:\n  {sel}: "{q(m)}"\n'
        if bind:
            s += f'  bind: {bind}\n'
        s += f'replace: "{q(r)}"\n'
        if imports:
            s += 'imports: [' + ', '.join(f'"{i}"' for i in imports) + ']\n'
        if pre:
            s += 'preconditions: [' + ', '.join(f'"{p}"' for p in pre) + ']\n'
        if prio is not None:
            s += f'priority: {prio}\n'
        s += f'confidence: 0.9\nprovenance: {{ source: agent, ref: "{q(self.ref)}" }}\ntests:\n'
        for ctx, before, after in tests:
            if ctx:
                s += f'  - context: "{q(ctx)}"\n    before: "{q(before)}"\n'
            else:
                s += f'  - before: "{q(before)}"\n'
            s += f'    after: "{q(after)}"\n'
        self.out.append(s)

    def type(self, src, dst, prio=None, pre=None, test=None, kind='adapter'):
        simple = src.replace('$', '.').rsplit('.', 1)[1]
        d = dst.replace('$', '.')
        if test is None:
            test = (None, f'import {src.replace("$", ".")};', f'import {d};')
        self.add('type-' + simple if '$' not in src else 'type-' + src.split('$')[0].rsplit('.', 1)[1] + '-' + simple,
                 'type', src, d, [test], kind=kind, prio=prio, pre=pre)

    def extends(self, src, dst):
        """the root of a ported hierarchy: 'class X extends <src>' -> the 1.19.2-API adapter base"""
        simple = src.rsplit('.', 1)[1]
        dsimple = dst.rsplit('.', 1)[1]
        self.add('extends-' + simple, 'type', src, dst,
                 [(f'import {src}', f'class L extends {simple} {{}}', f'class L extends {dst if simple == dsimple else dsimple} {{}}')],
                 pre=['extends'], prio=20)

    def call(self, m, r, test, recv=None, args=(), imports=None, pre=None, prio=None, kind='adapter', slug=None):
        parts = []
        if recv:
            parts.append(f'recv: "{recv}"')
        if args:
            parts.append('args: [' + ', '.join(f'"{a}"' for a in args) + ']')
        owner, rest = m.split('#')
        self.add(slug or ('call-' + owner.replace('$', '.').rsplit('.', 1)[1] + '-' + rest.split('(')[0]), 'call', m, r, [test],
                 kind=kind, bind='{ ' + ', '.join(parts) + ' }' if parts else None, imports=imports, pre=pre, prio=prio)

    def field(self, m, r, test, recv=None, imports=None, kind='adapter', slug=None, prio=None):
        owner, name = m.split('#')
        self.add(slug or ('field-' + owner.replace('$', '.').rsplit('.', 1)[1] + '-' + name), 'field', m, r, [test], kind=kind,
                 bind=f'{{ recv: "{recv}" }}' if recv else None, imports=imports, prio=prio)

    def new(self, m, r, test, args=(), imports=None, slug=None, pre=None, prio=None):
        owner = m.split('(')[0]
        self.add(slug or ('new-' + owner.replace('$', '.').rsplit('.', 1)[1]), 'new', m, r, [test],
                 bind='{ args: [' + ', '.join(f'"{a}"' for a in args) + '] }' if args else None, imports=imports, pre=pre, prio=prio)

    def write(self):
        p = os.path.join(OUT, f'modern-api-{self.topic}.rule.yaml')
        hdr = ''.join('# ' + l + '\n' for l in self.header.strip().splitlines())
        hdr += f'# Generated by rules/packs/adapters/1.19.2__1.7.10/modern_api_spec.py ({len(self.out)} rules); edit the spec, not this file.\n'
        open(p, 'w', encoding='utf-8', newline='\n').write(hdr + '---\n'.join(self.out))
        print(f'{p}: {len(self.out)} rules')
        return len(self.out)


